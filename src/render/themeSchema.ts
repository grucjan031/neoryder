import { z } from 'zod';
const color = z.string().regex(/^#[0-9a-fA-F]{6}$/);
const nonnegative = z.number().finite().nonnegative();
const unit = nonnegative.max(1);
export const themeSchema = z.object({
  id: z.string().regex(/^[a-zA-Z0-9_]+$/),
  render: z
    .object({
      concrete: color,
      asphalt: color,
      metal: color,
      facade: color,
      trim: color,
      glass: color,
      cable: color,
      paint: color,
      lacquer: color,
      rust: color,
      corrugated: color,
      plastic: color,
      hivis: color,
      rubber: color,
      wood: color,
      fabric: color,
      machine: color,
      paving: color,
      plaster: color,
      hazard: color,
      neon_amber: color,
      neon_green: color,
      neon_violet: color,
      neon_blue: color,
      neon_white: color,
      light_white: color,
      hemiSky: color,
      hemiGround: color,
      keyColor: color,
      citySurfaceDetail: unit,
      cityBumpStrength: nonnegative,
      cityHazardPeriod: z.number().finite().positive(),
      enemyRimStrength: nonnegative,
      enemyRimPower: nonnegative,
      reflectionStrength: nonnegative,
      reflectionDistortion: nonnegative,
      reflectionPuddles: unit,
      reflectionFloorTolerance: nonnegative,
      heightFogDensity: unit,
      heightFogFalloff: nonnegative,
      panoramaEnabled: unit,
      panoramaDensity: unit,
      panoramaHeight: nonnegative,
      panoramaWindowWarm: color,
      panoramaWindowCool: color,
      world: color,
      enemy: color,
      enemyGlow: color,
      interactive: color,
      player: color,
      power: color,
      outline: unit,
      outlineThickness: nonnegative,
      outlineDepthThreshold: nonnegative,
      outlineNormalThreshold: nonnegative,
      outlineColor: color,
      /** Opcjonalne: motyw bez nich dziedziczy kontur zależny od odległości z tuning. */
      outlineFadeNear: nonnegative.optional(),
      outlineFadeFar: nonnegative.optional(),
      outlineFarNormal: unit.optional(),
      outlineFarOuter: unit.optional(),
      hemiIntensity: nonnegative,
      keyIntensity: nonnegative,
      bloom: unit,
      postFx: unit,
      bloomStrength: nonnegative,
      bloomRadius: nonnegative,
      skyGradient: unit,
      skyFlash: unit,
      skyTop: color,
      skyHorizon: color,
      skyGradientHeight: nonnegative,
      fogStrength: unit,
      fogColor: color,
      fogNear: nonnegative,
      fogFar: nonnegative,
      viewmodelDepth: nonnegative,
      gridSize: nonnegative,
      gridContrast: unit,
      gridLineWidth: nonnegative,
      vignetteStrength: nonnegative,
      vignetteRadius: nonnegative,
      vignetteSoftness: nonnegative,
      damagePulseS: nonnegative,
      damagePulseMin: nonnegative,
      damagePulseHpGain: nonnegative,
      damageAberration: nonnegative,
      damageTint: nonnegative,
      damageTintColor: color,
      focusTint: nonnegative,
      focusTintColor: color,
      focusDesaturate: nonnegative,
      focusFadeInS: nonnegative,
      focusFadeOutS: nonnegative,
    })
    .refine((r) => r.fogFar > r.fogNear, {
      message: 'fogFar musi być większe od fogNear.',
    }),
  rain: z.object({
    enabled: z.boolean(),
    density: unit,
    speed: nonnegative,
    windX: z.number().finite(),
    color,
    opacity: unit,
    /** Rzadkie błyski burzy (częstość: tuning.city.stormRate). */
    storm: z.boolean().optional(),
  }),
});
export type Theme = z.infer<typeof themeSchema>;
